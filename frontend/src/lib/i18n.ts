const DICTS: Record<Lang, Dict> = { en, es, fr, pt, de, ru, ja, zh, ko };

export type TFn = (key: keyof typeof en) => string;

export function translator(lang: Lang): TFn {
  return (key) => DICTS[lang]?.[key] ?? en[key];
}

const CODES = Object.keys(LANGUAGES) as Lang[];

/**
 * Pick a language from what the browser actually asks for.
 *
 * `navigator.languages` is the user's ordered preference list, not just the one
 * top choice — someone on a German machine who prefers Japanese gets Japanese.
 * Region tags are matched loosely so pt-PT, pt-BR and pt all land on pt, and
 * zh-Hans / zh-CN / zh-TW all land on zh.
 */
export function detectLang(): Lang {
  if (typeof navigator === "undefined") return "en";
  const wanted = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const tag of wanted) {
    if (!tag) continue;
    const lower = tag.toLowerCase();
    const exact = CODES.find((c) => c === lower);
    if (exact) return exact;
    const base = lower.split("-")[0];
    const loose = CODES.find((c) => c === base);
    if (loose) return loose;
  }
  return "en";
}

/**
 * How a language appears in the picker: its own name, and — when it isn't the
 * one you're currently reading — its name in your language.
 *
 *   reading Spanish:  Español · English (Inglés) · Français (Francés)
 *   reading English:  English · Español (Spanish) · Français (French)
 *
 * Intl.DisplayNames already knows every one of these translations, so there's
 * no 9x9 table of language names to write or keep correct.
 */
export function languageLabel(code: Lang, current: Lang): string {
  const endonym = LANGUAGES[code];
  if (code === current) return endonym;
  try {
    const translated = new Intl.DisplayNames([current], { type: "language" }).of(DISPLAY_TAG[code] ?? code);
    if (!translated || translated.toLowerCase() === endonym.toLowerCase()) return endonym;
    // Spanish and French lowercase language names mid-sentence; this is a label.
    return `${endonym} (${translated[0].toUpperCase()}${translated.slice(1)})`;
  } catch {
    return endonym;   // very old browser: the endonym alone is still correct
  }
}
